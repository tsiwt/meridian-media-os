let current = "en";

export function setLanguage(lang) {
  current = messages[lang] ? lang : "en";
  document.documentElement.lang = current;
}

export function getLanguage() {
  return current;
}

export function t(key, fallback) {
  return messages[current]?.[key] ?? messages.en[key] ?? fallback ?? key;
}

export function bilingual(creative, field) {
  if (!creative) return "";
  if (current === "zh" && creative[`${field}Zh`]) return creative[`${field}Zh`];
  return creative[`${field}En`] ?? creative[field] ?? "";
}